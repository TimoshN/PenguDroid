//! GLES entry points with scalar floating-point arguments.
//!
//! i = core integer/pointer word, f = 32-bit float, d = 64-bit double.
//! Pointers to float data are integers and therefore are not listed here.
pub fn signature(name: &str) -> Option<&'static str> {
    Some(match name {
        "glAlphaFuncQCOM" => "if",
        "glBlendColor" => "ffff",
        "glClearBufferfi" => "iifi",
        "glClearColor" => "ffff",
        "glClearDepthf" => "f",
        "glDepthRangeIndexedfNV" | "glDepthRangeIndexedfOES" => "iff",
        "glDepthRangef" => "ff",
        "glDrawVkImageNV" => "iifffffffff",
        "glFramebufferFoveationParametersQCOM" => "iiifffff",
        "glGetPathSpacingNV" => "iiiiiffii",
        "glInterpolatePathsNV" => "iiif",
        "glIsPointInFillPathNV" => "iiff",
        "glIsPointInStrokePathNV" => "iff",
        "glLineWidth" => "f",
        "glMatrixFrustumEXT" | "glMatrixOrthoEXT" => "idddddd",
        "glMatrixRotatedEXT" => "idddd",
        "glMatrixRotatefEXT" => "iffff",
        "glMatrixScaledEXT" => "iddd",
        "glMatrixScalefEXT" => "ifff",
        "glMatrixTranslatedEXT" => "iddd",
        "glMatrixTranslatefEXT" => "ifff",
        "glMinSampleShading" | "glMinSampleShadingOES" => "f",
        "glPathGlyphIndexArrayNV" => "iiiiiiif",
        "glPathGlyphIndexRangeNV" => "iiiiifi",
        "glPathGlyphRangeNV" => "iiiiiiiif",
        "glPathGlyphsNV" => "iiiiiiiiif",
        "glPathMemoryGlyphIndexArrayNV" => "iiiiiiiif",
        "glPathParameterfNV" => "iif",
        "glPathStencilDepthOffsetNV" => "ff",
        "glPointAlongPathNV" => "iiifiiii",
        "glPolygonOffset" => "ff",
        "glPolygonOffsetClampEXT" => "fff",
        "glPrimitiveBoundingBox" | "glPrimitiveBoundingBoxEXT" | "glPrimitiveBoundingBoxOES" => "ffffffff",
        "glProgramUniform1f" | "glProgramUniform1fEXT" => "iif",
        "glProgramUniform2f" | "glProgramUniform2fEXT" => "iiff",
        "glProgramUniform3f" | "glProgramUniform3fEXT" => "iifff",
        "glProgramUniform4f" | "glProgramUniform4fEXT" => "iiffff",
        "glSampleCoverage" => "fi",
        "glSamplerParameterf" | "glTexParameterf" => "iif",
        "glTextureFoveationParametersQCOM" => "iiifffff",
        "glUniform1f" => "if",
        "glUniform2f" => "iff",
        "glUniform3f" => "ifff",
        "glUniform4f" => "iffff",
        "glVertexAttrib1f" => "if",
        "glVertexAttrib2f" => "iff",
        "glVertexAttrib3f" => "ifff",
        "glVertexAttrib4f" => "iffff",
        "glViewportIndexedfNV" | "glViewportIndexedfOES" => "iffff",
        "glViewportPositionWScaleNV" => "iff",
        _ => return None,
    })
}
